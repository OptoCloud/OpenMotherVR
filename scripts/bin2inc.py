"""Write binary files as C++ byte arrays.

    python -I scripts/bin2inc.py <out.inc> <name>=<file> [<name>=<file> ...]

Each file becomes `inline constexpr unsigned char <name>[] = {...};`.
"""
import pathlib
import sys


def main() -> None:
    out = pathlib.Path(sys.argv[1])
    lines = [f"// Generated by scripts/bin2inc.py. Do not edit.", ""]
    for spec in sys.argv[2:]:
        name, path = spec.split("=", 1)
        data = pathlib.Path(path).read_bytes()
        lines.append(f"// {pathlib.Path(path).name}, {len(data)} bytes")
        lines.append(f"inline constexpr unsigned char {name}[] = {{")
        for i in range(0, len(data), 16):
            lines.append("    " + " ".join(f"0x{b:02x}," for b in data[i:i + 16]))
        lines.append("};")
        lines.append("")
    out.write_text("\n".join(lines), newline="\n")


if __name__ == "__main__":
    main()
