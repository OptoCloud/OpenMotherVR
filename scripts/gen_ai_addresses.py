"""Generate src/hook/ai_address_tables.inc from the original dxgi.dll.

The original keeps one 127-entry table of AI.exe RVAs per supported build:
  - Patched_2020 (timestamp 0x5FD25676): written entry by entry in
    FUN_10001840, read here from its Ghidra decompile.
  - Original_2015 (timestamp 0x54E3199D): static initializer of the
    DAT_10066bc8 array in .data, read here from the PE file.
FUN_10001760 picks one based on the flag computed in FUN_10002250.

usage: gen_ai_addresses.py <dxgi.dll> <FUN_10001840 .c> <out.inc>
"""
import re
import struct
import sys

import pefile

COUNT = 127
TABLE_VA = 0x10066BC8


def main(dll, decomp, out):
    pe = pefile.PE(dll, fast_load=True)
    base = pe.OPTIONAL_HEADER.ImageBase
    raw = pe.get_data(TABLE_VA - base, 4 * COUNT)
    t2015 = list(struct.unpack(f"<{COUNT}I", raw))

    t2020 = [None] * COUNT
    src = open(decomp, encoding="utf-8").read()
    for idx, val in re.findall(r"in_ECX\[(0x[0-9a-f]+|\d+)\] = (0x[0-9a-f]+|\d+);", src):
        t2020[int(idx, 0)] = int(val, 0)
    # in_ECX[0] is written as "*in_ECX = ..." by the decompiler
    m = re.search(r"\*in_ECX = (0x[0-9a-f]+|\d+);", src)
    if m:
        t2020[0] = int(m.group(1), 0)
    missing = [i for i, v in enumerate(t2020) if v is None]
    if missing:
        sys.exit(f"FUN_10001840 decompile is missing indices: {missing}")

    with open(out, "w", newline="\n") as f:
        f.write("// Generated by scripts/gen_ai_addresses.py. Do not edit.\n")
        f.write("// AI.exe RVAs, index i = original global DAT_10066bc8 + 4*i.\n\n")
        for name, tbl in (("kAiRvas2015", t2015), ("kAiRvas2020", t2020)):
            f.write(f"inline constexpr std::array<std::uint32_t, {COUNT}> {name} = {{\n")
            for i in range(0, COUNT, 6):
                row = ", ".join(f"0x{v:08X}" for v in tbl[i:i + 6])
                f.write(f"    /* 0x{i:02X} */ {row},\n")
            f.write("};\n\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
